#!/usr/bin/env python3
"""
Generate ETL/ESTIMATED_VALUES.md — a provenance table of which Sites/Treatments
carry MODELLED (estimated) soil and climate values rather than values reported in
the source publications.

Reads the two applied worksheets and the site/treatment map dumped from the DB:
    ETL/soil_enrichment.csv   (per-field Source: summary | soilgrids | soilgrids_scaled)
    ETL/site_climate.csv      (per-field Source: summary | nasa_power)
    /tmp/site_trt_map.tsv      SiteID, SiteName, TreatmentID, ExperimentName

Only the gridded/climatology sources are "estimated":
    soilgrids / soilgrids_scaled  -> SoilGrids v2.0 (ISRIC)
    nasa_power                    -> NASA POWER climatology
"summary" is authoritative (from the Dorich export) and is NOT flagged.
"""

import csv
import os

ETL = os.path.dirname(os.path.abspath(__file__))
EST_SOIL = {"soilgrids", "soilgrids_scaled"}
EST_CLIM = {"nasa_power"}
SOIL_LABEL = {"SandMean": "Sand", "SiltMean": "Silt", "ClayMean": "Clay",
              "pHMean": "pH", "BulkDensityMean": "BD", "SOMMean": "SOM"}


def parse_source(cell):
    """'Sand:soilgrids;pH:summary' -> {'SandMean': 'soilgrids', 'pHMean': 'summary'}."""
    out = {}
    for part in (cell or "").split(";"):
        if ":" in part:
            f, s = part.split(":", 1)
            out[f.strip()] = s.strip()
    return out


def ranges(ids):
    """[1,2,3,7,8] -> '1–3, 7–8'."""
    ids = sorted(set(int(i) for i in ids))
    if not ids:
        return ""
    out, lo, prev = [], ids[0], ids[0]
    for i in ids[1:]:
        if i == prev + 1:
            prev = i
            continue
        out.append(f"{lo}" if lo == prev else f"{lo}–{prev}")
        lo = prev = i
    out.append(f"{lo}" if lo == prev else f"{lo}–{prev}")
    return ", ".join(out)


def main():
    smap = list(csv.DictReader(open("/tmp/site_trt_map.tsv"), delimiter="\t"))
    site_name = {}
    site_refs = {}
    tid_site = {}
    site_tids = {}
    for r in smap:
        sid = r["SiteID"]
        site_name[sid] = r["SiteName"]
        if r["ExperimentName"].strip():
            site_refs.setdefault(sid, set()).add(r["ExperimentName"].strip())
        tid_site[r["TreatmentID"]] = sid
        site_tids.setdefault(sid, set()).add(r["TreatmentID"])

    # estimated soil fields, per site (collect which treatments + which fields)
    site_soil_est = {}   # sid -> {field -> set(tids)}
    for r in csv.DictReader(open(os.path.join(ETL, "soil_enrichment.csv"))):
        tid = r["TreatmentID"]
        sid = tid_site.get(tid)
        if sid is None:
            continue
        for f, s in parse_source(r["Source"]).items():
            if s in EST_SOIL:
                site_soil_est.setdefault(sid, {}).setdefault(f, set()).add(tid)

    # estimated climate, per site
    site_clim_est = {}   # sid -> set(fields)
    for r in csv.DictReader(open(os.path.join(ETL, "site_climate.csv"))):
        sid = r["SiteID"]
        for f, s in parse_source(r["Source"]).items():
            if s in EST_CLIM:
                site_clim_est.setdefault(sid, set()).add(f)

    sids = sorted(set(site_soil_est) | set(site_clim_est), key=int)

    lines = []
    lines.append("# Estimated (modelled) soil & climate values\n")
    lines.append(
        "Values filled from a gridded fallback rather than the source publication / "
        "Dorich export. **Soil** estimates come from **SoilGrids v2.0** (ISRIC, 0–30 cm "
        "depth-weighted), **climate** from **NASA POWER** climatology. Everything not "
        "listed here was filled from the authoritative Dorich `Summary` export "
        "(`Source=summary`). `soilgrids_scaled` = a measured clay% was kept and "
        "sand/silt rescaled around it (see ETL/README.md §5).\n")
    lines.append(
        f"_Generated by `build_provenance.py`. {len(sids)} sites carry at least one "
        "estimated value._\n")
    lines.append(
        "> Note: the legacy rows (Treatment 1–334) were loaded with measured **texture** "
        "but no pH/BD/SOM, so those three are uniformly SoilGrids-estimated there; their "
        "Sand/Silt/Clay remain the original measured values and are not listed below.\n")
    lines.append("| Site | Name | Study ref(s) | Treatments | Estimated soil | Estimated climate |")
    lines.append("|---:|---|---|---|---|---|")

    for sid in sids:
        name = site_name.get(sid, "").replace("|", "/")
        refs = ", ".join(sorted(site_refs.get(sid, []))) or "—"
        soil = site_soil_est.get(sid, {})
        # treatments at this site touched by ANY soil estimate
        soil_tids = set().union(*soil.values()) if soil else set()
        soil_fields = ", ".join(SOIL_LABEL[f] for f in
                                ["SandMean", "SiltMean", "ClayMean", "pHMean",
                                 "BulkDensityMean", "SOMMean"] if f in soil) or "—"
        clim_fields = ", ".join(f for f in ("MAP", "MAT") if f in site_clim_est.get(sid, set())) or "—"
        trt_disp = ranges(soil_tids) if soil_tids else "—"
        lines.append(f"| {sid} | {name} | {refs} | {trt_disp} | {soil_fields} | {clim_fields} |")

    # footer counts
    n_soil_fills = sum(len(t) for s in site_soil_est.values() for t in s.values())
    n_clim_sites = len(site_clim_est)
    lines.append("")
    lines.append(f"**Totals:** {n_soil_fills} estimated soil field-values across "
                 f"{len(site_soil_est)} sites; estimated climate at {n_clim_sites} sites.")

    out = os.path.join(ETL, "ESTIMATED_VALUES.md")
    with open(out, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines) + "\n")
    print(f"wrote {out}: {len(sids)} sites, {n_soil_fills} soil field-values, {n_clim_sites} climate sites")


if __name__ == "__main__":
    main()
